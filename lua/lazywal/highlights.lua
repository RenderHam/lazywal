--- Highlight groups for the `lazywal` colorscheme.
--- Every group is derived from the (percentage-adjusted) ANSI palette.
local M = {}

---@param c table logical color roles
---@param opts table config options
---@return table<string, table>
function M.build(c, opts)
	local h = {}
	local italic_comment = opts.styles and opts.styles.comments and opts.styles.comments.italic
		or false

	local function set(group, spec)
		h[group] = spec
	end

	-- Core editor
	set("Normal", { fg = c.fg, bg = c.bg })
	set("NormalNC", { fg = c.fg, bg = c.bg })
	set("NormalFloat", { fg = c.fg, bg = c.bg_alt })
	set("FloatBorder", { fg = c.grey, bg = c.bg_alt })
	set("FloatFooter", { fg = c.grey, bg = c.bg_alt })
	set("Comment", { fg = c.grey, italic = italic_comment })
	set("Constant", { fg = c.cyan })
	set("String", { fg = c.green })
	set("Character", { fg = c.green })
	set("Number", { fg = c.yellow })
	set("Float", { fg = c.yellow })
	set("Boolean", { fg = c.yellow })
	set("Identifier", { fg = c.fg })
	set("Function", { fg = c.blue })
	set("Statement", { fg = c.magenta })
	set("Conditional", { fg = c.magenta })
	set("Repeat", { fg = c.magenta })
	set("Operator", { fg = c.magenta })
	set("Keyword", { fg = c.magenta })
	set("Exception", { fg = c.bright_red })
	set("Tag", { fg = c.blue })
	set("PreProc", { fg = c.magenta })
	set("Include", { fg = c.magenta })
	set("Define", { fg = c.magenta })
	set("Macro", { fg = c.magenta })
	set("Type", { fg = c.cyan })
	set("StorageClass", { fg = c.cyan })
	set("Structure", { fg = c.cyan })
	set("Typedef", { fg = c.cyan })
	set("Special", { fg = c.yellow })
	set("SpecialChar", { fg = c.yellow })
	set("Delimiter", { fg = c.fg })
	set("Ignore", { fg = c.grey })
	set("Error", { fg = c.bright_red, bg = c.bg_alt })
	set("Todo", { fg = c.yellow, bold = true })
	set("Underlined", { underline = true })
	set("Bold", { bold = true })
	set("Italic", { italic = true })

	-- Selection / search
	set("Visual", { bg = c.bg_highlight })
	set("VisualNC", { bg = c.bg_highlight })
	set("Select", { bg = c.bg_highlight })
	set("Search", { fg = c.bg, bg = c.yellow })
	set("IncSearch", { fg = c.bg, bg = c.bright_yellow })
	set("CurSearch", { fg = c.bg, bg = c.red })
	set("Substitute", { fg = c.bg, bg = c.red })
	set("MatchParen", { fg = c.yellow, bold = true, underline = true })

	-- Gutter / lines
	set("LineNr", { fg = c.grey })
	set("CursorLineNr", { fg = c.fg, bold = true })
	set("CursorLine", { bg = c.bg_alt })
	set("CursorColumn", { bg = c.bg_alt })
	set("ColorColumn", { bg = c.bg_alt })
	set("Folded", { fg = c.grey, bg = c.bg_alt })
	set("FoldColumn", { fg = c.grey })
	set("SignColumn", { fg = c.grey, bg = c.bg })
	set("NonText", { fg = c.grey })
	set("EndOfBuffer", { fg = c.grey })
	set("Whitespace", { fg = c.grey })
	set("Conceal", { fg = c.grey })
	set("VertSplit", { fg = c.grey })
	set("WinSeparator", { fg = c.grey })

	-- Status / tab line
	set("StatusLine", { fg = c.fg, bg = c.bg_alt })
	set("StatusLineNC", { fg = c.grey, bg = c.bg })
	set("TabLine", { fg = c.grey, bg = c.bg })
	set("TabLineFill", { fg = c.grey, bg = c.bg })
	set("TabLineSel", { fg = c.fg, bg = c.bg_alt })
	set("Title", { fg = c.blue, bold = true })
	set("ModeMsg", { fg = c.fg })
	set("MoreMsg", { fg = c.green })
	set("Question", { fg = c.green })
	set("Directory", { fg = c.blue })

	-- Popup menus
	set("Pmenu", { fg = c.fg, bg = c.bg_alt })
	set("PmenuSel", { fg = c.bg, bg = c.blue })
	set("PmenuKind", { fg = c.cyan, bg = c.bg_alt })
	set("PmenuKindSel", { fg = c.bg, bg = c.blue })
	set("PmenuExtra", { fg = c.grey, bg = c.bg_alt })
	set("PmenuExtraSel", { fg = c.bg, bg = c.blue })
	set("PmenuSbar", { bg = c.bg_alt })
	set("PmenuThumb", { bg = c.grey })
	set("WildMenu", { fg = c.bg, bg = c.blue })

	-- Messages / diff / spell
	set("ErrorMsg", { fg = c.bright_red })
	set("WarningMsg", { fg = c.yellow })
	set("DiffAdd", { fg = c.green, bg = c.bg_add })
	set("DiffChange", { fg = c.yellow, bg = c.bg_change })
	set("DiffDelete", { fg = c.red, bg = c.bg_delete })
	set("DiffText", { fg = c.blue, bg = c.bg_change })
	set("Added", { fg = c.green })
	set("Changed", { fg = c.yellow })
	set("Removed", { fg = c.red })
	set("SpellBad", { undercurl = true, sp = c.red })
	set("SpellCap", { undercurl = true, sp = c.blue })
	set("SpellRare", { undercurl = true, sp = c.magenta })
	set("SpellLocal", { undercurl = true, sp = c.cyan })

	-- Treesitter
	set("@function", { fg = c.blue })
	set("@function.builtin", { fg = c.bright_blue })
	set("@function.call", { fg = c.blue })
	set("@method", { fg = c.blue })
	set("@method.call", { fg = c.blue })
	set("@constructor", { fg = c.cyan })
	set("@variable", { fg = c.fg })
	set("@variable.builtin", { fg = c.bright_magenta })
	set("@variable.parameter", { fg = c.fg })
	set("@parameter", { fg = c.fg })
	set("@variable.member", { fg = c.fg })
	set("@property", { fg = c.fg })
	set("@field", { fg = c.fg })
	set("@constant", { fg = c.cyan })
	set("@constant.builtin", { fg = c.bright_cyan })
	set("@string", { fg = c.green })
	set("@string.escape", { fg = c.yellow })
	set("@string.special", { fg = c.bright_green })
	set("@character", { fg = c.green })
	set("@number", { fg = c.yellow })
	set("@boolean", { fg = c.yellow })
	set("@float", { fg = c.yellow })
	set("@type", { fg = c.cyan })
	set("@type.builtin", { fg = c.bright_cyan })
	set("@class", { fg = c.cyan })
	set("@interface", { fg = c.cyan })
	set("@module", { fg = c.cyan })
	set("@namespace", { fg = c.cyan })
	set("@keyword", { fg = c.magenta })
	set("@keyword.function", { fg = c.magenta })
	set("@keyword.operator", { fg = c.magenta })
	set("@keyword.return", { fg = c.magenta })
	set("@keyword.exception", { fg = c.bright_red })
	set("@conditional", { fg = c.magenta })
	set("@repeat", { fg = c.magenta })
	set("@operator", { fg = c.magenta })
	set("@comment", { fg = c.grey, italic = italic_comment })
	set("@comment.documentation", { fg = c.grey, italic = italic_comment })
	set("@annotation", { fg = c.yellow })
	set("@attribute", { fg = c.yellow })
	set("@tag", { fg = c.blue })
	set("@tag.attribute", { fg = c.cyan })
	set("@tag.delimiter", { fg = c.grey })
	set("@punctuation.delimiter", { fg = c.fg })
	set("@punctuation.bracket", { fg = c.fg })
	set("@punctuation.special", { fg = c.yellow })
	set("@markup.heading", { fg = c.blue, bold = true })
	set("@markup.link", { fg = c.cyan })
	set("@markup.link.label", { fg = c.cyan })
	set("@markup.link.url", { fg = c.green })
	set("@markup.strong", { bold = true })
	set("@markup.italic", { italic = true })
	set("@markup.strikethrough", { strikethrough = true })
	set("@markup.raw", { fg = c.green })
	set("@markup.list", { fg = c.yellow })
	set("@diff.plus", { fg = c.green })
	set("@diff.minus", { fg = c.red })
	set("@diff.delta", { fg = c.yellow })

	-- LSP semantic tokens
	set("@lsp.type.class", { fg = c.cyan })
	set("@lsp.type.function", { fg = c.blue })
	set("@lsp.type.method", { fg = c.blue })
	set("@lsp.type.variable", { fg = c.fg })
	set("@lsp.type.parameter", { fg = c.fg })
	set("@lsp.type.property", { fg = c.fg })
	set("@lsp.type.enum", { fg = c.cyan })
	set("@lsp.type.interface", { fg = c.cyan })
	set("@lsp.type.namespace", { fg = c.cyan })
	set("@lsp.type.keyword", { fg = c.magenta })
	set("@lsp.type.comment", { fg = c.grey })
	set("@lsp.type.string", { fg = c.green })
	set("@lsp.type.number", { fg = c.yellow })
	set("@lsp.type.operator", { fg = c.magenta })
	set("@lsp.mod.deprecated", { strikethrough = true })
	set("@lsp.typemod.function.defaultLibrary", { fg = c.bright_blue })
	set("@lsp.typemod.variable.readonly", { fg = c.cyan })

	-- Diagnostics
	local severities = {
		Error = c.red,
		Warn = c.yellow,
		Info = c.blue,
		Hint = c.cyan,
		Ok = c.green,
	}
	for name, color in pairs(severities) do
		set("Diagnostic" .. name, { fg = color })
		set("DiagnosticFloating" .. name, { fg = color })
		set("DiagnosticSign" .. name, { fg = color })
		set("DiagnosticUnderline" .. name, { undercurl = true, sp = color })
		set("DiagnosticVirtualText" .. name, { fg = color })
	end
	set("TinyInlineDiagnosticVirtualText", { fg = c.grey })
	set("TinyInlineDiagnosticVirtualTextArrow", { fg = c.grey })
	set("TinyInlineInvDiagnosticVirtualText", { fg = c.fg })

	-- blink.cmp
	set("BlinkCmpMenu", { fg = c.fg, bg = c.bg_alt })
	set("BlinkCmpMenuBorder", { fg = c.grey, bg = c.bg_alt })
	set("BlinkCmpDoc", { fg = c.fg, bg = c.bg_alt })
	set("BlinkCmpDocBorder", { fg = c.grey, bg = c.bg_alt })
	set("BlinkCmpSignatureHelp", { fg = c.fg, bg = c.bg_alt })
	set("BlinkCmpSignatureHelpBorder", { fg = c.grey, bg = c.bg_alt })
	set("BlinkCmpLabel", { fg = c.fg })
	set("BlinkCmpLabelDeprecated", { fg = c.grey, strikethrough = true })
	set("BlinkCmpLabelMatch", { fg = c.blue, bold = true })
	set("BlinkCmpSource", { fg = c.grey })
	set("BlinkCmpGhostText", { fg = c.grey })

	-- gitsigns
	set("GitSignsAdd", { fg = c.green })
	set("GitSignsChange", { fg = c.yellow })
	set("GitSignsDelete", { fg = c.red })
	set("GitSignsTopdelete", { fg = c.red })
	set("GitSignsChangedelete", { fg = c.yellow })
	set("GitSignsAddNr", { fg = c.green })
	set("GitSignsChangeNr", { fg = c.yellow })
	set("GitSignsDeleteNr", { fg = c.red })
	set("GitSignsAddLn", { bg = c.bg_add })
	set("GitSignsChangeLn", { bg = c.bg_change })
	set("GitSignsDeleteLn", { bg = c.bg_delete })
	set("GitSignsCurrentLineBlame", { fg = c.grey })

	-- noice
	set("NoiceCmdlinePopup", { fg = c.fg, bg = c.bg_alt })
	set("NoiceCmdlinePopupBorder", { fg = c.grey, bg = c.bg_alt })
	set("NoiceCmdlinePopupTitle", { fg = c.blue, bg = c.bg_alt })
	set("NoiceCmdlineIcon", { fg = c.cyan })
	set("NoiceConfirmBorder", { fg = c.grey })
	set("NoiceFormatLevelInfo", { fg = c.blue })
	set("NoiceFormatLevelWarn", { fg = c.yellow })
	set("NoiceFormatLevelError", { fg = c.red })
	set("NoiceFormatLevelDebug", { fg = c.grey })

	-- which-key
	set("WhichKeyFloat", { fg = c.fg, bg = c.bg_alt })
	set("WhichKeyNormal", { fg = c.fg, bg = c.bg_alt })
	set("WhichKeyGroup", { fg = c.blue })
	set("WhichKeySeparator", { fg = c.grey })
	set("WhichKeyDesc", { fg = c.fg })

	-- mini.icons / mini.files
	set("MiniIconsAzure", { fg = c.blue })
	set("MiniIconsBlue", { fg = c.blue })
	set("MiniIconsCyan", { fg = c.cyan })
	set("MiniIconsGreen", { fg = c.green })
	set("MiniIconsGrey", { fg = c.grey })
	set("MiniIconsOrange", { fg = c.yellow })
	set("MiniIconsPink", { fg = c.magenta })
	set("MiniIconsPurple", { fg = c.magenta })
	set("MiniIconsRed", { fg = c.red })
	set("MiniIconsYellow", { fg = c.yellow })
	set("MiniFilesBorder", { fg = c.grey })
	set("MiniFilesTitle", { fg = c.blue })
	set("MiniFilesCursorLine", { bg = c.bg_alt })
	set("MiniFilesDirectory", { fg = c.blue })
	set("MiniFilesFile", { fg = c.fg })

	-- snacks
	set("SnacksBackdrop", { fg = c.grey })
	set("SnacksPicker", { fg = c.fg, bg = c.bg_alt })
	set("SnacksPickerBorder", { fg = c.grey, bg = c.bg_alt })
	set("SnacksPickerInput", { fg = c.fg, bg = c.bg_alt })
	set("SnacksPickerList", { fg = c.fg, bg = c.bg_alt })
	set("SnacksPickerPreview", { fg = c.fg, bg = c.bg_alt })
	set("SnacksPickerPrompt", { fg = c.blue })
	set("SnacksPickerSelected", { fg = c.blue, bold = true })
	set("SnacksPickerMatch", { fg = c.yellow, bold = true })
	set("SnacksDiffAdd", { fg = c.green })
	set("SnacksDiffDelete", { fg = c.red })
	set("SnacksDiffChange", { fg = c.yellow })

	return h
end

return M
